const DICTS: Record<Lang, Record<Key, string>> = { en, zh };

/** Exposed for tests: assert dictionary parity between languages. */
export const dictionaries = DICTS;

interface I18nState {
  lang: Lang;
  setLang: (lang: Lang) => void;
}

function initialLang(): Lang {
  try {
    const stored = localStorage.getItem('ntk_lang');
    if (stored === 'zh' || stored === 'en') return stored;
  } catch {
    // no localStorage (SSR / tests) — fall through
  }
  try {
    return navigator.language?.toLowerCase().startsWith('zh') ? 'zh' : 'en';
  } catch {
    return 'en';
  }
}

export const useI18n = create<I18nState>((set) => ({
  lang: initialLang(),
  setLang: (lang) => {
    try {
      localStorage.setItem('ntk_lang', lang);
    } catch {
      // ignore
    }
    try {
      document.documentElement.lang = lang === 'zh' ? 'zh-CN' : 'en';
    } catch {
      // no DOM (tests)
    }
    set({ lang });
  },
}));

/** Translate with the store's current language, from anywhere (incl. non-React modules). */
export function tOf(key: Key): string {
  return DICTS[useI18n.getState().lang][key];
}

/** Translate + interpolate {0},{1},… from anywhere. */
export function tfOf(key: Key, ...args: (string | number)[]): string {
  let s = tOf(key);
  args.forEach((a, i) => {
    s = s.replaceAll(`{${i}}`, String(a));
  });
  return s;
}

/** React hook: `const t = useT(); t('smartAll')` */
export function useT() {
  const lang = useI18n((s) => s.lang);
  return (key: Key) => DICTS[lang][key];
}

/** React hook with interpolation: `f('daysLeft', 3)` */
export function useTF() {
  const lang = useI18n((s) => s.lang);
  return (key: Key, ...args: (string | number)[]) => {
    let s = DICTS[lang][key];
    args.forEach((a, i) => {
      s = s.replaceAll(`{${i}}`, String(a));
    });
    return s;
  };
}

/** Map known server error messages to the current language. */
export function serverError(message: string): string {
  const lang = useI18n.getState().lang;
  if (lang !== 'zh') return message;
  const table: [RegExp, string][] = [
    [/Invalid email or password/i, '邮箱或密码错误。'],
    [/invite code/i, '注册需要有效的邀请码。'],
    [/already registered/i, '该邮箱已被注册。'],
    [/at least 8 characters/i, '请输入有效邮箱，密码至少 8 位。'],
  ];
  for (const [re, zhMsg] of table) {
    if (re.test(message)) return zhMsg;
  }
  return message;
}
